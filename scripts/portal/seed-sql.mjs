#!/usr/bin/env node
/**
 * Writes supabase/seed.sql: every listing in lib/data/projects.json as a row of the portal's listings
 * table, published exactly when the site shows it today (LISTED_DEVELOPERS and HIDDEN_LISTINGS in
 * lib/listings.ts). Images keep their built keys, so nothing has to be uploaded. Run once, after the
 * migration, on a new portal database.
 *
 *   node scripts/portal/seed-sql.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const projects = JSON.parse(readFileSync(new URL("lib/data/projects.json", root)));
const specs = JSON.parse(readFileSync(new URL("lib/data/project-images.json", root)));
const src = readFileSync(new URL("lib/listings.ts", root), "utf8");
const devs = JSON.parse((src.match(/LISTED_DEVELOPERS: string\[\] \| null = (\[[^\]]*\]|null)/) || [])[1] || "null");
const hidden = JSON.parse((src.match(/HIDDEN_LISTINGS: string\[\] = (\[[^\]]*\])/) || [])[1] || "[]");

const rows = projects.map((p, i) => ({
  slug: p.slug,
  ref: p.ref,
  title: p.title,
  developer: p.developer,
  developer_url: p.developerUrl,
  community: p.community,
  area: p.area,
  types: p.types,
  status: p.status,
  price: p.price,
  price_note: p.priceNote,
  beds: p.beds,
  beds_max: p.bedsMax,
  size: p.size,
  summary: p.summary,
  description: p.description,
  features: p.features,
  amenities: p.amenities,
  handover: p.handover,
  plan: p.plan,
  plan_label: p.planLabel,
  permit: p.permit,
  project_number: p.projectNumber,
  escrow: p.escrow,
  source: p.source,
  checked: p.checked,
  images: p.images.map((key) => ({ key, alt: specs[key]?.alt ?? "" })),
  published: (!devs || devs.includes(p.developer)) && !hidden.includes(p.slug),
  sort: i,
}));
const cols = Object.keys(rows[0]);
const json = JSON.stringify(rows);
if (json.includes("$seed$")) throw new Error("seed JSON contains the quote tag");
writeFileSync(
  new URL("supabase/seed.sql", root),
  `-- Generated by scripts/portal/seed-sql.mjs from lib/data/projects.json. ${rows.length} listings, ${rows.filter((r) => r.published).length} published.\n` +
    `insert into public.listings (${cols.join(", ")})\nselect ${cols.join(", ")}\nfrom jsonb_populate_recordset(null::public.listings, $seed$${json}$seed$::jsonb)\non conflict (slug) do nothing;\n`,
);
console.log(`seed.sql: ${rows.length} listings, ${rows.filter((r) => r.published).length} published`);
